    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
    int condicion = 0;
    

    if (optSimple.isSelected()) {
        condicion = 120;
    } else if (optDoble.isSelected()) {
        condicion = 200;
    } else if (optSuite.isSelected()) {
        condicion = 350;
            
    }
    double descuento = 0;

    if (chkReservaAnticipada.isSelected()) {
        descuento = descuento + 0.10; 
    }
    if (chkBuffet.isSelected()) {
        descuento = descuento + 30;  
    }
    if (chkSauna.isSelected()) {
        descuento = descuento + 80; 
    }

    double des = condicion * descuento;
    double montoTotal = condicion - des;


    

    JLIST.addElement(txtHuesped.getText() + " - S/. " +
    String.format("%.2f", montoTotal));

        // TODO add your handling code here:
    }//GEN-LAST:event_btnCalcularActionPerformed

